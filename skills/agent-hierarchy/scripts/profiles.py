#!/usr/bin/env python3
"""Assemble bundled Codex profiles. Never installs profiles or starts sessions."""
import argparse
import json
from pathlib import Path
import re
import sys

SKILL = Path(__file__).resolve().parents[1]
HEADER = '# Generated by scripts/profiles.py; edit references/profile-sources instead.\n'
FIELDS = {'name', 'description', 'reasoning_effort', 'sources'}


def render_profiles(skill=SKILL):
    """Return complete TOML assets, validating all sources before any write."""
    source_dir = (Path(skill) / 'references/profile-sources').resolve()
    manifest = json.loads((source_dir / 'profiles.json').read_text(encoding='utf-8'))
    if not isinstance(manifest, list) or not manifest:
        raise ValueError('profiles.json must be a nonempty list')
    result = {}
    for spec in manifest:
        if not isinstance(spec, dict) or set(spec) != FIELDS:
            raise ValueError('Each profile needs exactly: ' + ', '.join(sorted(FIELDS)))
        name = spec['name']
        if not isinstance(name, str) or not re.fullmatch(r'[a-z][a-z0-9_]*', name):
            raise ValueError('Invalid profile name')
        filename = name + '.toml'
        if filename in result or name in {'default', 'worker', 'explorer'}:
            raise ValueError('Duplicate or reserved profile name: ' + name)
        description = spec['description']
        if not isinstance(description, str) or not description.strip():
            raise ValueError(name + ': missing description')
        effort = spec['reasoning_effort']
        if effort not in (None, 'medium', 'high', 'xhigh'):
            raise ValueError(name + ': unsupported reasoning effort')
        paths = spec['sources']
        if not isinstance(paths, list) or not paths or any(not isinstance(p, str) for p in paths):
            raise ValueError(name + ': sources must be a nonempty list of paths')
        parts, seen = [], set()
        for relative in paths:
            path = (source_dir / relative).resolve()
            if Path(relative).is_absolute() or not path.is_relative_to(source_dir) or path.suffix != '.md':
                raise ValueError(name + ': source must be a Markdown file inside profile-sources')
            if path in seen:
                raise ValueError(name + ': duplicate source ' + relative)
            seen.add(path)
            content = path.read_text(encoding='utf-8').strip()
            if not content or any(ord(c) < 32 and c not in '\n\t' for c in content) or '\x7f' in content:
                raise ValueError(name + ': empty source or unsupported control character in ' + relative)
            parts.append(content)
        instructions = '\n\n'.join(parts) + '\n'
        # TOML multiline basic strings preserve readable generated diffs. Escape
        # quotes/backslashes so source text cannot terminate the string or add keys.
        escaped = instructions.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t')
        lines = [HEADER.rstrip(), '# Complete instructions; project model and permissions are inherited.',
                 'name = ' + json.dumps(name),
                 'description = ' + json.dumps(description, ensure_ascii=False)]
        if effort is not None:
            lines.append('model_reasoning_effort = ' + json.dumps(effort))
        lines.extend(['service_tier = "default"', '', 'developer_instructions = """', escaped + '"""', ''])
        result[filename] = '\n'.join(lines)
    return result


def asset_directory(skill):
    skill = Path(skill).resolve()
    output = skill / 'assets/agents'
    if (skill / 'assets').is_symlink() or output.is_symlink():
        raise ValueError('Refusing symlinked asset directory')
    return output


def check_profiles(skill=SKILL):
    expected = render_profiles(skill)
    output = asset_directory(skill)
    errors = []
    for filename, content in expected.items():
        path = output / filename
        if path.is_symlink():
            errors.append(filename + ': symlink is not a generated asset')
        elif not path.is_file():
            errors.append(filename + ': missing generated asset')
        elif path.read_text(encoding='utf-8') != content:
            errors.append(filename + ': generated asset is stale or edited')
    for path in sorted(output.glob('*.toml')):
        if path.name not in expected:
            errors.append(path.name + ': unexpected asset; review manually')
    return errors


def write_profiles(skill=SKILL):
    expected = render_profiles(skill)
    output = asset_directory(skill)
    # Preserve unrecognized files; this command is regeneration, not cleanup.
    for path in output.glob('*.toml'):
        if path.name not in expected or path.is_symlink():
            raise ValueError('Refusing unexpected or symlinked asset: ' + path.name)
    for filename in expected:
        path = output / filename
        if path.exists() and not path.is_file():
            raise ValueError('Not a regular asset file: ' + filename)
    output.mkdir(parents=True, exist_ok=True)
    for filename, content in expected.items():
        path = output / filename
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            path.write_text(content, encoding='utf-8')
    return len(expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true', help='Regenerate bundled assets only')
    mode.add_argument('--check', action='store_true', help='Check bundled assets without writing')
    args = parser.parse_args()
    try:
        if args.write:
            print('Generated {} bundled profiles; nothing installed or launched.'.format(write_profiles()))
        else:
            errors = check_profiles()
            if errors:
                print('\n'.join(errors), file=sys.stderr)
                return 1
            print('Bundled profiles match their sources.')
    except (ValueError, OSError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
